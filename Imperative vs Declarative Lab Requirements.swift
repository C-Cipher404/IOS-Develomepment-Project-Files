/*
 Imperative vs. Declarative

 Declarative programming is when you tell the computer what
 you want to happen instead of explaining every step to make
 it happen. Imperative programming is more about giving
 step-by-step instructions. People often prefer declarative
 programming because it makes code easier to read, understand,
 and maintain. An example would be decorating a room.
 Imperative would be telling someone exactly where to put
 every piece of furniture, while declarative would be showing
 them a picture of how you want the room to look. SwiftUI
 uses declarative programming because we describe what the
 screen should look like, and SwiftUI handles updating it
 when things change. We can follow this pattern by using
 views, state, and modifiers instead of manually controlling
 every update.
*/

